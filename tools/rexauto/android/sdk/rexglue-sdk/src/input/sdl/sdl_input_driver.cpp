void SDLInputDriver::UpdateXCapabilities(ControllerState& state) {
  assert(state.sdl);
  uint16_t cap_flags = 0x0;

  // The RAWINPUT driver combines and enhances input from different APIs. For
  // details, see `SDL_rawinputjoystick.c`. This correlation however has latency
  // which might confuse games calling `GetCapabilities()` (The power level is
  // only available after the controller has been "touched"). Generally that
  // should not be a problem, when in doubt disable the RAWINPUT driver via hint
  // (env var).

  if (SDL_GetJoystickConnectionState(SDL_GetGamepadJoystick(state.sdl)) ==
      SDL_JOYSTICK_CONNECTION_WIRELESS) {
    cap_flags |= X_INPUT_CAPS_WIRELESS;
  }

  // Check if all navigational buttons are present
  static constexpr std::array<SDL_GamepadButton, 6> nav_buttons = {
      SDL_GAMEPAD_BUTTON_START,     SDL_GAMEPAD_BUTTON_BACK,      SDL_GAMEPAD_BUTTON_DPAD_UP,
      SDL_GAMEPAD_BUTTON_DPAD_DOWN, SDL_GAMEPAD_BUTTON_DPAD_LEFT, SDL_GAMEPAD_BUTTON_DPAD_RIGHT,
  };
  for (auto it = nav_buttons.begin(); it < nav_buttons.end(); it++) {
    if (!SDL_GamepadHasButton(state.sdl, *it)) {
      cap_flags |= X_INPUT_CAPS_NO_NAVIGATION;
      break;
    }
  }

  auto& c = state.caps;
  c.type = 0x01;      // XINPUT_DEVTYPE_GAMEPAD
  c.sub_type = 0x01;  // XINPUT_DEVSUBTYPE_GAMEPAD
  c.flags = cap_flags;
  c.gamepad.buttons = 0xF3FF | (REXCVAR_GET(guide_button) ? X_INPUT_GAMEPAD_GUIDE : 0x0);
  c.gamepad.left_trigger = 0xFF;
  c.gamepad.right_trigger = 0xFF;
  c.gamepad.thumb_lx = static_cast<int16_t>(0xFFFFu);
  c.gamepad.thumb_ly = static_cast<int16_t>(0xFFFFu);
  c.gamepad.thumb_rx = static_cast<int16_t>(0xFFFFu);
  c.gamepad.thumb_ry = static_cast<int16_t>(0xFFFFu);
  c.vibration.left_motor_speed = 0xFFFFu;
  c.vibration.right_motor_speed = 0xFFFFu;
}

void SDLInputDriver::QueueControllerUpdate() {
  // (Hunt v1.4.6, A4-R6-04.) Pump synchronously on the UI thread instead of
  // queueing the pump: the old fire-and-forget CallInUIThread returned at
  // once, so GetDeviceState drained pending_events_ BEFORE the queued
  // SDL_PumpEvents ran and a physical pad was systematically one guest poll
  // behind (~100-170 ms at 6-10 fps). SDL_PumpEvents is main-thread-only
  // (SDL_events.h), so it cannot run on the guest thread directly; the
  // synchronous UI-thread call is the correct shape. CallInUIThreadSynchronous
  // runs inline when the caller already is the UI thread (no deadlock
  // there), and the UI thread is the SDL event loop (SDL_WaitEvent), so the
  // pump runs promptly.
  // (Hunt v1.4.6 ronda 4, A4-R4-03.) Bounded variant: the unbounded wait
  // hung the guest poll for the whole SDL pause (the UI thread is parked
  // on the pause semaphore, so the queued pump cannot run). A timed-out
  // pump is safe here and only here: SDL_PumpEvents only feeds the event
  // watch, which already buffered the events into pending_events_, and
  // DrainAndLock drains them below; the queued pump still runs when the UI
  // thread resumes, so no event is lost — the poll just proceeds with the
  // buffered state instead of waiting out the pause. 1000 ms, like the
  // A4-R3-02 pause waits. The shared CallInUIThreadSynchronous keeps its
  // unbounded contract on purpose (its xam_ui callers delete the dialog
  // when it returns false — a timeout there would run dialog->Then on a
  // deleted dialog), so only this call site uses the timeout variant.
  if (!attached_window_) {
    return;
  }
  if (!attached_window_->app_context().CallInUIThreadSynchronousWithTimeout(
          [this]() { SDL_PumpEvents(); }, std::chrono::milliseconds(1000))) {
    // Expected during a pause; log once so a long pause does not spam.
    static std::atomic<int> pump_timeout_count{0};
    if (pump_timeout_count.fetch_add(1) == 0) {
      REXLOG_WARN("SDL input pump timed out (UI thread paused); continuing with buffered events");
    }
  }
}

// Check if the analog inputs exceed their thresholds to become a button press
// and build the bitfield.
inline uint64_t SDLInputDriver::AnalogToKeyfield(const X_INPUT_GAMEPAD& gamepad) const {
  uint64_t f = 0;

  f |= static_cast<uint64_t>(gamepad.left_trigger > HID_SDL_TRIGG_THRES) << 16;
  f |= static_cast<uint64_t>(gamepad.right_trigger > HID_SDL_TRIGG_THRES) << 17;

  auto thumb_x = static_cast<int16_t>(gamepad.thumb_lx);
  auto thumb_y = static_cast<int16_t>(gamepad.thumb_ly);
  for (size_t i = 0; i <= 8; i = i + 8) {
    uint64_t u = thumb_y > HID_SDL_THUMB_THRES;
    uint64_t d = thumb_y < ~HID_SDL_THUMB_THRES;
    uint64_t r = thumb_x > HID_SDL_THUMB_THRES;
    uint64_t l = thumb_x < ~HID_SDL_THUMB_THRES;
    if (u && l) {
      u = l = 0;
      f |= uint64_t(1) << (22 + i);
    }
    if (u && r) {
      u = r = 0;
      f |= uint64_t(1) << (23 + i);
    }
    if (d && r) {
      d = r = 0;
      f |= uint64_t(1) << (24 + i);
    }
    if (d && l) {
      d = l = 0;
      f |= uint64_t(1) << (25 + i);
    }
    f |= u << (18 + i);
    f |= d << (19 + i);
    f |= r << (20 + i);
    f |= l << (21 + i);

    thumb_x = static_cast<int16_t>(gamepad.thumb_rx);
    thumb_y = static_cast<int16_t>(gamepad.thumb_ry);
  }
  return f;
}

